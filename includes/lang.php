// Get current language from session or default to 'en'
if (session_status() === PHP_SESSION_NONE) session_start();
$GLOBALS['rpms_lang'] = $_SESSION['rpms_lang'] ?? 'en';

// Handle language switch
if (isset($_GET['lang']) && isset($GLOBALS['rpms_translations'][$_GET['lang']])) {
    $_SESSION['rpms_lang'] = $_GET['lang'];
    $GLOBALS['rpms_lang'] = $_GET['lang'];
}

/**
 * Translate a key
 */
function __($key) {
    $lang = $GLOBALS['rpms_lang'] ?? 'en';
    return $GLOBALS['rpms_translations'][$lang][$key]
        ?? $GLOBALS['rpms_translations']['en'][$key]
        ?? $key;
}

/**
 * Get available languages
 */
function getLanguages() {
    return [
        'en' => 'English',
        'fil' => 'Filipino',
        'ceb' => 'Cebuano',
    ];
}

/**
 * Language switcher HTML snippet
 */
function langSwitcher() {
    $current = $GLOBALS['rpms_lang'] ?? 'en';
    $langs = getLanguages();
    $url = strtok($_SERVER['REQUEST_URI'], '?');
    $qs = $_GET;

    $html = '<div class="lang-switcher" style="display:inline-flex;gap:4px;align-items:center">';
    foreach ($langs as $code => $name) {
        $qs['lang'] = $code;
        $active = ($code === $current) ? 'font-weight:700;color:#0e9e52;' : 'color:#6b8878;';
        $html .= '<a href="' . $url . '?' . http_build_query($qs) . '" style="font-size:.78rem;text-decoration:none;padding:3px 8px;border-radius:4px;' . $active . '">' . $name . '</a>';
    }
    $html .= '</div>';
    return $html;
}
